"""Reconstruct a campaign's cumulative state at each decision point.

The single subtle idea in Phase 1: there are TWO clocks.

  * Spend accrues in real (wall-clock) time — ``timestamp`` on spend rows.
  * Revenue is only visible when a conversion POSTS — ``postback_time`` on
    conversion rows. The buyer counts conversions as they post.

So "the moment the campaign had accumulated N conversions" is the wall-clock
instant T_N when the N-th conversion *posts*. At that instant the buyer sees:
    observed_revenue = payouts of the N posted conversions
    observed_spend   = ALL spend accrued up to T_N  (including spend whose
                       conversions have not posted yet)
=> observed ROI is structurally biased LOW. This is exactly what the naive rule
acts on, so it is what we must simulate.

We also compute a LAG-ALIGNED view for the same instant: credit spend with every
conversion it *generated* (spend-time <= T_N), whether or not it has posted yet.
The gap between observed and lag-aligned ROI is the money that is "already earned
but not yet posted" — the part of an early loss that is lag, not fundamentals.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import pandas as pd

from ..datasource import EventCols


@dataclass
class DecisionState:
    campaign_id: str
    n_conversions: int          # the decision point requested (5, 10, ...)
    actual_conversions: int     # cumulative conversions actually reached at T_N
    decision_time: pd.Timestamp  # T_N, when cumulative conversions crossed N
    observed_spend: float
    observed_revenue: float
    observed_roi: float          # what the buyer sees (lag-biased when postbacks lag)
    aligned_revenue: float       # revenue of conversions generated by spend<=T_N
    aligned_roi: float           # lag-removed ROI at the same instant
    post_profit: float           # net profit earned AFTER T_N (revenue-spend)


def _conv_time(conv: pd.DataFrame) -> pd.Series:
    """The clock the buyer counts conversions on: postback time if we have it,
    otherwise the stat/spend time. Real tracker rollups (e.g. RedTrack) attribute
    conversions back to click time and carry NO postback column, so we fall back
    to the row timestamp — which makes observed ROI == aligned ROI (no visible
    lag), the correct behaviour when the source is already click-attributed."""
    if EventCols.POSTBACK_TS in conv.columns:
        return conv[EventCols.POSTBACK_TS].fillna(conv[EventCols.TS])
    return conv[EventCols.TS]


def reconstruct_campaign(events: pd.DataFrame, decision_points: list[int]) -> list[DecisionState]:
    """Return the observed/aligned state at each decision point for one campaign.

    Works for BOTH row shapes:
      * synthetic — separate spend rows and per-conversion rows (with postback_time);
      * real tracker rollups — aggregated rows carrying spend, clicks, conversions
        and revenue together per (date, hour, source), no postback_time.
    We accumulate by the CONVERSION COUNT (rows may carry many conversions), so a
    decision point N is the instant cumulative conversions first reach >= N.
    """
    conv = events[events[EventCols.CONVERSIONS] > 0].copy()
    spend = events[events[EventCols.SPEND] > 0].copy()
    if conv.empty or spend.empty:
        return []

    # --- conversion stream by POST time (buyer's view), weighted by count ------
    conv["_ctime"] = _conv_time(conv)
    conv_posted = conv.sort_values("_ctime")
    post_times = conv_posted["_ctime"].to_numpy()
    cum_conv = np.cumsum(conv_posted[EventCols.CONVERSIONS].to_numpy())
    cum_rev_posted = np.cumsum(conv_posted[EventCols.REVENUE].to_numpy())
    total_conv = int(cum_conv[-1])

    # --- spend stream by accrual time -----------------------------------------
    spend_sorted = spend.sort_values(EventCols.TS)
    spend_times = spend_sorted[EventCols.TS].to_numpy()
    spend_cum = np.cumsum(spend_sorted[EventCols.SPEND].to_numpy())
    total_spend = spend_cum[-1]

    # --- generation-time conversion stream (lag-aligned) ----------------------
    conv_gen = conv.sort_values(EventCols.TS)
    gen_times = conv_gen[EventCols.TS].to_numpy()
    gen_rev_cum = np.cumsum(conv_gen[EventCols.REVENUE].to_numpy())
    total_rev = gen_rev_cum[-1]

    out: list[DecisionState] = []
    for n in decision_points:
        if n > total_conv:
            continue
        # first stat-row at which cumulative conversions reach >= n
        idx = int(np.searchsorted(cum_conv, n, side="left"))
        t_n = post_times[idx]
        observed_revenue = float(cum_rev_posted[idx])
        actual_conv = int(cum_conv[idx])

        # spend accrued up to and including T_N
        s_idx = np.searchsorted(spend_times, t_n, side="right")
        observed_spend = float(spend_cum[s_idx - 1]) if s_idx > 0 else 0.0

        # lag-aligned revenue: all conversions whose SPEND/gen-time <= T_N
        g_idx = np.searchsorted(gen_times, t_n, side="right")
        aligned_revenue = float(gen_rev_cum[g_idx - 1]) if g_idx > 0 else 0.0

        observed_roi = (observed_revenue - observed_spend) / observed_spend if observed_spend > 0 else 0.0
        aligned_roi = (aligned_revenue - observed_spend) / observed_spend if observed_spend > 0 else 0.0

        # profit earned strictly AFTER the decision instant (observable; survivors)
        spend_after = float(total_spend - observed_spend)
        rev_after = float(total_rev - aligned_revenue)
        post_profit = rev_after - spend_after

        out.append(DecisionState(
            campaign_id=str(events[EventCols.ID].iloc[0]),
            n_conversions=n,
            actual_conversions=actual_conv,
            decision_time=pd.Timestamp(t_n),
            observed_spend=observed_spend,
            observed_revenue=observed_revenue,
            observed_roi=observed_roi,
            aligned_revenue=aligned_revenue,
            aligned_roi=aligned_roi,
            post_profit=post_profit,
        ))
    return out


def reconstruct_all(events: pd.DataFrame, decision_points: list[int]) -> pd.DataFrame:
    """Reconstruct decision states for every campaign in `events`."""
    records = []
    for cid, grp in events.groupby(EventCols.ID, sort=False):
        for st in reconstruct_campaign(grp, decision_points):
            records.append(vars(st))
    return pd.DataFrame(records)
